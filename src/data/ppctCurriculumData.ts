// Generate standard periods based on MoET regulations for THCS
export function getStandardPeriodsForSubject(subject: string): { total: number; term1: number; term2: number } {
  const s = subject.toLowerCase();
  if (s.includes('khtn1') || s.includes('hóa') || s.includes('hoa')) {
    return { total: 46, term1: 24, term2: 22 }; // Phân môn Hóa học
  }
  if (s.includes('khtn2') || s.includes('vật lí') || s.includes('vật lý') || s.includes('ly') || s.includes('lí')) {
    return { total: 47, term1: 24, term2: 23 }; // Phân môn Vật lý
  }
  if (s.includes('khtn3') || s.includes('sinh') || s.includes('sinh học')) {
    return { total: 47, term1: 24, term2: 23 }; // Phân môn Sinh học
  }
  if (s.includes('toán') || s.includes('văn') || (s.includes('khtn') && !s.includes('1') && !s.includes('2') && !s.includes('3')) || s.includes('khoa học')) {
    return { total: 140, term1: 72, term2: 68 }; // 4 periods/week
  }
  if (s.includes('tiếng anh') || s.includes('anh') || s.includes('lịch sử và địa lí') || s.includes('hđtn') || s.includes('trải nghiệm')) {
    return { total: 105, term1: 54, term2: 51 }; // 3 periods/week
  }
  if (s.includes('thể chất') || s.includes('gdtc') || s.includes('nghệ thuật') || s.includes('sử') || s.includes('địa')) {
    return { total: 70, term1: 36, term2: 34 }; // 2 periods/week
  }
  // GDCD, Tin học, Công nghệ, Âm nhạc, Mĩ thuật, GD ĐP
  return { total: 35, term1: 18, term2: 17 }; // 1 period/week
}

